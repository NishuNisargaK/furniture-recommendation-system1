    # generated by LabelEncoder during data cleaning.
    raw_products["product_id"] = (
        raw_products["product_id"].astype(str).str.strip()
    )

    sorted_ids = sorted(raw_products["product_id"].unique())

    id_mapping = {
        original_id: index
        for index, original_id in enumerate(sorted_ids)
    }

