# ---------------- SIMILARITY ----------------
def cosine_similarity(a, b):
    dot = sum(x * y for x, y in zip(a, b))
    mag_a = math.sqrt(sum(x * x for x in a))
    mag_b = math.sqrt(sum(y * y for y in b))

    if mag_a == 0 or mag_b == 0:
        return 0

    return dot / (mag_a * mag_b)


def get_recommendations(product_id, count=5):
    feature_columns = [
        col for col in features.columns if col != "product_id"
    ]

    feature_matrix = features[feature_columns].fillna(0)

    selected = features.index[
        features["product_id"] == product_id
    ]

    if len(selected) == 0:
        return []

    selected_index = selected[0]
    selected_vector = feature_matrix.loc[selected_index].tolist()

    results = []

    for index, row in feature_matrix.iterrows():
        if index == selected_index:
            continue

        score = cosine_similarity(
            selected_vector,
            row.tolist()
        )

        recommended_id = features.loc[index, "product_id"]

        matching_product = products[
            products["product_id"] == recommended_id
        ]

        if not matching_product.empty:
            results.append((matching_product.iloc[0], score))

    results.sort(key=lambda x: x[1], reverse=True)
    return results[:count]


